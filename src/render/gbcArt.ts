/**
 * All of microbomber's pixel art as indexed data under Game Boy Color rules
 * (`gbcPalette.ts`). The renderer bakes these with a palette, so recolours (crystal
 * colour, damage flash, a bomb's last-second flash) are palette swaps, not new art.
 *
 * Sprites: '.' transparent, '1' light, '2' mid, '3' dark, one sprite palette each.
 * Background tiles: '0'..'3' (light to dark), one background palette per 8x8 quarter
 * (top-left, top-right, bottom-left, bottom-right).
 */
import type { BgPaletteId, ObjPaletteId } from './gbcPalette';

export interface ObjSprite {
  pal: ObjPaletteId;
  rows: readonly string[];
}

export interface BgTile {
  quads: readonly [BgPaletteId, BgPaletteId, BgPaletteId, BgPaletteId];
  rows: readonly string[];
}

function obj(pal: ObjPaletteId, rows: string[]): ObjSprite {
  return { pal, rows };
}

function bg(quads: BgTile['quads'], rows: string[]): BgTile {
  return { quads, rows };
}

